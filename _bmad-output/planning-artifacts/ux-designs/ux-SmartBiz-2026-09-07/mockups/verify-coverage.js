#!/usr/bin/env node
'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const EXPECTED_COUNT = 76;
const here = __dirname;
const paths = {
  epics: path.resolve(here, '../../../epics.md'),
  map: path.join(here, 'screen-map.js'),
  renderer: path.join(here, 'mockups.js'),
  styles: path.join(here, 'mockups.css'),
  html: path.join(here, 'all-screens.html'),
  manifest: path.join(here, 'coverage-manifest.js')
};
const source = Object.fromEntries(Object.entries(paths).filter(([key]) => key !== 'manifest').map(([key, file]) => [key, fs.readFileSync(file, 'utf8')]));
const planned = [...source.epics.matchAll(/^### Story (\d+\.\d+): (.+)$/gm)].map(match => ({ id: match[1], title: match[2].trim() }));
const sandbox = { window: {}, Set };
vm.runInNewContext(source.map, sandbox, { filename: paths.map });
const designed = sandbox.window.SMARTBIZ_SCREEN_MAP;
const failures = [];
const allowedKinds = new Set(['proof','auth','form','state','detail','table','list','flow','report']);
const allowedModes = new Set(['phone','desktop']);
const allowedShells = new Set(['onboarding','app','proof']);
const allowedActions = new Set(['commit','navigate','inspect','export']);
const customRequired = ['1.2','1.4','1.9','2.1','4.5','4.8','4.9','4.10','4.11','4.14','5.2','5.8','5.10','6.3','6.4','6.5','7.2','10.2','10.5','11.3','12.1','12.2'];

function duplicates(values) { return [...new Set(values.filter((value, index) => values.indexOf(value) !== index))]; }
function hash(text) { return crypto.createHash('sha256').update(text).digest('hex').slice(0, 16); }
function nonempty(value) { return typeof value === 'string' && value.trim().length > 0; }
function writeManifest(passed) {
  const manifest = {
    passed,
    planned: planned.length,
    designed: Array.isArray(designed) ? designed.length : 0,
    failures,
    generatedAt: new Date().toISOString(),
    hashes: { epics: hash(source.epics), screenMap: hash(source.map), renderer: hash(source.renderer), styles: hash(source.styles), html: hash(source.html) }
  };
  fs.writeFileSync(paths.manifest, `/* Generated by verify-coverage.js; do not edit. */\nwindow.SMARTBIZ_COVERAGE = ${JSON.stringify(manifest, null, 2)};\n`);
}

if (planned.length !== EXPECTED_COUNT) failures.push(`epics.md contains ${planned.length} stories; fixed contract requires ${EXPECTED_COUNT}.`);
const plannedDuplicates = duplicates(planned.map(story => story.id));
if (plannedDuplicates.length) failures.push(`Duplicate planned IDs: ${plannedDuplicates.join(', ')}.`);
if (!Array.isArray(designed)) failures.push('screen-map.js did not expose an array.');

if (Array.isArray(designed)) {
  if (designed.length !== EXPECTED_COUNT) failures.push(`screen-map.js contains ${designed.length} stories; fixed contract requires ${EXPECTED_COUNT}.`);
  const designedDuplicates = duplicates(designed.map(story => story.id));
  if (designedDuplicates.length) failures.push(`Duplicate designed IDs: ${designedDuplicates.join(', ')}.`);

  for (const plan of planned) {
    const screen = designed.find(item => item.id === plan.id);
    if (!screen) failures.push(`Missing screen for Story ${plan.id}: ${plan.title}.`);
    else if (screen.title !== plan.title) failures.push(`Title mismatch for Story ${plan.id}: “${screen.title}”.`);
  }
  for (const screen of designed) {
    const plannedStory = planned.find(story => story.id === screen.id);
    if (!plannedStory) failures.push(`Extra screen ${screen.id}: ${screen.title}.`);
    const epicFromId = Number(String(screen.id).split('.')[0]);
    if (screen.epic !== epicFromId) failures.push(`Story ${screen.id} has epic ${screen.epic}, expected ${epicFromId}.`);
    if (!allowedKinds.has(screen.kind)) failures.push(`Story ${screen.id} has invalid kind ${screen.kind}.`);
    if (!allowedModes.has(screen.primaryMode) || !allowedModes.has(screen.secondaryMode) || screen.primaryMode === screen.secondaryMode) failures.push(`Story ${screen.id} requires distinct phone/desktop primaryMode and secondaryMode.`);
    if ('mode' in screen) failures.push(`Story ${screen.id} exposes legacy mode; use primaryMode.`);
    if (!allowedShells.has(screen.shell)) failures.push(`Story ${screen.id} has invalid shell ${screen.shell}.`);
    if (!nonempty(screen.responsive)) failures.push(`Story ${screen.id} has no responsive contract.`);
    if (!nonempty(screen.appRoute) || !screen.appRoute.startsWith('/')) failures.push(`Story ${screen.id} has invalid appRoute.`);
    if (screen.mockupHash !== `#story/${screen.id}`) failures.push(`Story ${screen.id} has invalid mockupHash.`);
    if (!nonempty(screen.prototypeJourneyUrl) || !screen.prototypeJourneyUrl.endsWith(`/journeys/${screen.id}`)) failures.push(`Story ${screen.id} has invalid prototypeJourneyUrl.`);
    if (!screen.actionModel || !allowedActions.has(screen.actionModel.kind) || !nonempty(screen.actionModel.label) || typeof screen.actionModel.sticky !== 'boolean') failures.push(`Story ${screen.id} has invalid actionModel.`);
    else if (screen.actionModel.sticky !== (screen.actionModel.kind === 'commit')) failures.push(`Story ${screen.id} may use sticky action only for a commit.`);

    if (!Array.isArray(screen.proofs) || screen.proofs.length !== 3) failures.push(`Story ${screen.id} must have exactly three structured proofs.`);
    else {
      const proofIds = screen.proofs.map(proof => proof.id);
      if (new Set(proofIds).size !== 3) failures.push(`Story ${screen.id} proof IDs are not unique.`);
      screen.proofs.forEach((proof, index) => {
        const expectedId = `${screen.id}-proof-${index + 1}`;
        if (proof.id !== expectedId || !nonempty(proof.label) || proof.locator !== `[data-proof-id="${proof.id}"]`) failures.push(`Story ${screen.id} proof ${index + 1} is not stable/addressable.`);
      });
    }

    if (!Array.isArray(screen.variants) || screen.variants.length === 0) failures.push(`Story ${screen.id} has no addressable variants.`);
    else {
      const variantIds = screen.variants.map(variant => variant.id);
      if (new Set(variantIds).size !== variantIds.length) failures.push(`Story ${screen.id} has duplicate variant IDs.`);
      const coveredProofs = new Set();
      screen.variants.forEach(variant => {
        if (!variant.id.startsWith(`${screen.id}-`) || !nonempty(variant.label) || !nonempty(variant.state) || !Array.isArray(variant.proofIds) || variant.proofIds.length === 0) failures.push(`Story ${screen.id} has an invalid variant.`);
        (variant.proofIds || []).forEach(id => {
          if (!screen.proofs.some(proof => proof.id === id)) failures.push(`Story ${screen.id} variant ${variant.id} names unknown proof ${id}.`);
          coveredProofs.add(id);
        });
      });
      screen.proofs.forEach(proof => { if (!coveredProofs.has(proof.id)) failures.push(`Story ${screen.id} proof ${proof.id} is not assigned to a variant.`); });
    }
  }
}

if (!source.renderer.includes('data-proof-id=') || !source.renderer.includes('${proofGrid(story)}')) failures.push('Renderer does not place stable proof locators inside every device frame.');
for (const id of customRequired) if (!source.renderer.includes(`case '${id}':`)) failures.push(`Story ${id} requires a custom renderer.`);
if (!source.renderer.includes('inventory-handoff-pack-slip') || !source.renderer.includes('Inventory Staff pack slip')) failures.push('Story 5.2 lacks its addressable Inventory Staff pack-slip exception.');
if (!source.renderer.includes('function notFound')) failures.push('Renderer lacks an explicit unknown-story Not Found state.');
if (!source.html.includes('coverage-manifest.js') || !source.html.includes('screen-map.js') || !source.html.includes('mockups.js')) failures.push('all-screens.html does not load map, generated manifest, and renderer in order.');
if (!source.styles.includes('grid-template-columns: 244px') || !source.styles.includes('.phone-tabs')) failures.push('Responsive shells do not include the required 244px rail and phone tab bar.');
if (!source.styles.includes('@media (prefers-reduced-motion: reduce)')) failures.push('Reduced-motion contract is not rendered.');

writeManifest(failures.length === 0);
if (failures.length) {
  console.error(`Mockup gate FAILED (${failures.length} issues)\n- ${failures.join('\n- ')}`);
  process.exit(1);
}
console.log(`Mockup gate PASSED — ${EXPECTED_COUNT}/${EXPECTED_COUNT} stories, responsive contracts, variants, and 228 in-frame proofs verified.`);
